import { describe, expect, it } from "vitest";
import { bucketOf, daysFromNow, isPastAppt } from "@/lib/appt-days";

/**
 * "เหลืออีกกี่วัน" ของนัดหมาย — ต้องนับเป็น **วันในปฏิทินไทย** ไม่ใช่ช่วง 24 ชั่วโมง
 *
 * ของเดิมใช้ Math.ceil((appt - now) / 86400000) ซึ่งพังสองชั้นพร้อมกัน
 *   1) new Date("2026-10-09T08:00:00") ตีความตาม timezone ของเครื่องที่รัน
 *      worker รันด้วย UTC เวลานัดที่โรงพยาบาลจึงเลื่อนไป 7 ชั่วโมง
 *   2) Math.ceil ของเศษลบคืน -0 และ `-0 < 0` เป็น false
 *      นัดที่ผ่านไปแล้วไม่ถึง 24 ชม. จึงตกไปเข้าเงื่อนไข "วันนี้"
 *
 * อาการที่เจอจริง: เช้าวันที่ 10 ต.ค. นัดของวันที่ 9 ขึ้นป้าย "วันนี้"
 * และถูกจัดอยู่ในกลุ่ม "วันนี้"
 */
const at = (y: number, m: number, d: number, h = 0, min = 0) =>
  Date.UTC(y, m - 1, d, h - 7, min); // เวลาไทย -> epoch

describe("นับวันของนัดหมายตามปฏิทินไทย", () => {
  const now = at(2026, 10, 10, 7, 13); // 10 ต.ค. 2569 07:13 เวลาไทย

  it("นัดเมื่อวาน ต้องเป็นอดีต ไม่ใช่วันนี้ (เคสที่เจอจริง)", () => {
    expect(daysFromNow("2026-10-09T08:00:00", now)).toBe(-1);
    expect(bucketOf(-1)).toBe("ผ่านมาแล้ว");
  });

  it("นัดวันนี้ตอนบ่าย = 0 วัน", () => {
    expect(daysFromNow("2026-10-10T14:00:00", now)).toBe(0);
    expect(bucketOf(0)).toBe("วันนี้");
  });

  /** ของเดิมได้ 0 เพราะ 07:00 ถึง 06:00 ของพรุ่งนี้ห่างกันไม่ถึง 24 ชม. */
  it("นัดพรุ่งนี้เช้า = 1 วัน แม้ห่างกันไม่ถึง 24 ชั่วโมง", () => {
    expect(daysFromNow("2026-10-11T06:00:00", now)).toBe(1);
    expect(bucketOf(1)).toBe("สัปดาห์นี้");
  });

  it("นัดวันนี้ตอนเช้าที่เพิ่งผ่านไป ยังเป็นวันนี้ แต่ถือว่าเลยเวลาแล้ว", () => {
    expect(daysFromNow("2026-10-10T06:00:00", now)).toBe(0);
    expect(isPastAppt("2026-10-10T06:00:00", now)).toBe(true);
    expect(isPastAppt("2026-10-10T08:00:00", now)).toBe(false);
  });

  it("ข้ามเดือนและข้ามปีได้", () => {
    expect(daysFromNow("2026-11-09T08:00:00", now)).toBe(30);
    expect(daysFromNow("2027-01-10T08:00:00", now)).toBe(92);
  });

  /**
   * เที่ยงคืนครึ่งของไทยคือ 17:30 ของเมื่อวานใน UTC — จุดที่ของเดิมเพี้ยนแน่นอน
   * เพราะ worker รันด้วย UTC
   */
  it("ตีสองของไทย ยังนับว่าเป็นวันนั้นของไทย ไม่ใช่วันก่อนหน้าแบบ UTC", () => {
    const tiny = at(2026, 10, 10, 2, 0);
    expect(daysFromNow("2026-10-10T09:00:00", tiny)).toBe(0);
    expect(daysFromNow("2026-10-09T09:00:00", tiny)).toBe(-1);
  });

  it("กลุ่มตาม screen-blueprint §6.4", () => {
    expect(bucketOf(7)).toBe("สัปดาห์นี้");
    expect(bucketOf(8)).toBe("เดือนนี้");
    expect(bucketOf(30)).toBe("เดือนนี้");
    expect(bucketOf(31)).toBe("ในอนาคต");
  });
});
