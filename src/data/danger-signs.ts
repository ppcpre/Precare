/**
 * อาการที่แสดงจริง หลังกรองตามสถานะตั้งครรภ์
 *
 * CDC ระบุว่ารายการนี้ใช้ถึง 1 ปีหลังคลอด แต่บางข้อแยกกันชัด — ตอนท้องมี
 * "ลูกดิ้นน้อยลง" ส่วนหลังคลอดมี "เลือดชุ่มผ้าอนามัย" การแสดงข้อที่ไม่เกี่ยวกับ
 * ช่วงของตัวเองทำให้รายการยาวขึ้นโดยไม่ได้ช่วยอะไร
 */
export function signsFor(section: DangerSection, phase: Phase): DangerSign[] {
  return section.signs.filter((s) => s.phase === "both" || s.phase === phase);
}
