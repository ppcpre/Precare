/** ช่วงที่แสดงอาการนั้น — ใช้เฉพาะหมวดคนท้อง */
export type Phase = "pregnant" | "postpartum" | "both";

export interface DangerSign {
  id: string;
  label: string;
  /** ข้อย่อยที่เห็นเมื่อกดขยาย */
  details: string[];
  phase: Phase;
  /**
   * สำหรับหมวด "สิ่งที่คนรอบตัวเห็นก่อน" เท่านั้น — ชี้ว่าบรรทัดนี้มาจากอาการข้อไหน
   *
   * หมวดนั้นไม่ใช่เนื้อหาใหม่ แต่เป็นการหยิบข้อย่อยมาจัดใหม่ในมุมของคนที่ไม่ได้
   * มีอาการเอง ทุกบรรทัดต้องสืบกลับไปที่รายการ CDC ได้ ไม่งั้นมันจะค่อยๆ
   * กลายเป็นรายการที่เราแต่งเอง
   */
  derivedFrom?: string[];
}

export interface DangerSection {
  id: string;
  title: string;
  /** คำกำกับสั้นๆ ใต้หัวข้อ — ตัดได้ถ้าไม่จำเป็น หน้านี้ยิ่งสั้นยิ่งดี */
  note?: string;
  /** กรอบหนา สำหรับหมวดที่ต้องรีบที่สุดในกลุ่มนั้น */
  urgent?: boolean;
  /** ข้อความท้ายหมวด — ใช้เฉพาะตอนเป็น "สิ่งที่ต้องทำ" ไม่ใช่คำอธิบาย */
  action?: string;
  signs: DangerSign[];
}

export interface DangerGroup {
  id: "pregnancy" | "elderly" | "child";
  name: string;
  /** บรรทัดบอกใบ้บนการ์ดหน้าแรก ให้รู้ว่ากดเข้าไปเจออะไร */
  hint: string;
  sections: DangerSection[];
  /** ปุ่มโทร รพ. ที่ฝากครรภ์ โผล่เฉพาะหมวดนี้ */
  showHospital?: boolean;
  /** ปิดท้ายหมวด */
  footer?: string;
}

