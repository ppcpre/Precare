/**
 * ตัดสินว่าแอปที่เปิดอยู่เก่ากว่าเซิร์ฟเวอร์หรือยัง
 *
 * แยกออกมาเป็นฟังก์ชันล้วนเพราะเงื่อนไข "เมื่อไหร่ควรโหลดใหม่" คือจุดที่พลาดแล้ว
 * เจ็บที่สุด — ตัดสินผิดทางหนึ่งคือผู้ใช้ค้างอยู่กับบิลด์เก่าแล้วกดอะไรก็ error
 * ผิดอีกทางคือหน้ารีโหลดวนไม่รู้จบจนใช้งานไม่ได้เลย
 */
export interface SkewCheck {
  /** รหัสบิลด์ที่ฝังอยู่ในบันเดิลที่กำลังรันอยู่ */
  mine: string | undefined;
  /** รหัสบิลด์ที่เซิร์ฟเวอร์ตอบมา */
  theirs: unknown;
  /** เคยสั่งโหลดใหม่เพราะเรื่องนี้ไปแล้วหรือยังในแท็บนี้ */
  reloadedBefore: boolean;
}

export function shouldReload({ mine, theirs, reloadedBefore }: SkewCheck): boolean {
  // ไม่รู้รหัสฝั่งใดฝั่งหนึ่ง = ตัดสินไม่ได้ ห้ามเดา เพราะเดาผิดแล้วรีโหลดวน
  if (typeof theirs !== "string" || !theirs || theirs === "unknown") return false;
  if (!mine) return false;
  if (mine === theirs) return false;
  /**
   * โหลดใหม่ได้ครั้งเดียวต่อแท็บ
   *
   * ถ้าโหลดใหม่แล้วรหัสยังไม่ตรง (เช่น CDN ยังคืนของเก่าอยู่ หรือ env ตั้งผิด)
   * การรีโหลดซ้ำจะกลายเป็นวนไม่รู้จบ ซึ่งแย่กว่าปล่อยให้ใช้บิลด์เก่าต่อไป
   */
  return !reloadedBefore;
}
